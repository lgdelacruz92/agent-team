// Persists tickets and looks them up by local ID or unique Vikunja task ID.
import type { DatabaseSync } from "node:sqlite"

// SQLite INTEGER is 64-bit; numeric IDs must fit JavaScript's safe integer range.
export interface TicketRecord {
  id: number
  vikunjaTaskId: number
  title: string
  status: string
  priority: number
  presentOnBoard: boolean
}

export type TicketInput = Omit<TicketRecord, "id">

const columns = "id, vikunja_task_id AS vikunjaTaskId, title, status, priority, present_on_board AS presentOnBoard"

function readTicket(row: unknown): TicketRecord | undefined {
  if (!row) return undefined
  const ticket = row as Omit<TicketRecord, "presentOnBoard"> & { presentOnBoard: number }
  return { ...ticket, presentOnBoard: ticket.presentOnBoard === 1 }
}

// Uses a shared connection; closing it is the caller's responsibility.
export class TicketStore {
  constructor(private readonly database: DatabaseSync) {}

  // Local IDs are generated by SQLite; duplicate Vikunja IDs are rejected.
  create(ticket: TicketInput): TicketRecord {
    const row = this.database.prepare(`
      INSERT INTO tickets (vikunja_task_id, title, status, priority, present_on_board)
      VALUES (?, ?, ?, ?, ?) RETURNING ${columns}
    `).get(ticket.vikunjaTaskId, ticket.title, ticket.status, ticket.priority, Number(ticket.presentOnBoard))
    return readTicket(row)!
  }

  get(id: number): TicketRecord | undefined {
    return readTicket(this.database.prepare(`SELECT ${columns} FROM tickets WHERE id = ?`).get(id))
  }

  getByVikunjaTaskId(vikunjaTaskId: number): TicketRecord | undefined {
    return readTicket(this.database.prepare(`SELECT ${columns} FROM tickets WHERE vikunja_task_id = ?`).get(vikunjaTaskId))
  }

  list(): TicketRecord[] {
    return this.database.prepare(`SELECT ${columns} FROM tickets ORDER BY id`).all().map((row) => readTicket(row)!)
  }

  // Replaces mutable fields; returns undefined when the local ID does not exist.
  update(id: number, ticket: TicketInput): TicketRecord | undefined {
    const row = this.database.prepare(`
      UPDATE tickets SET vikunja_task_id = ?, title = ?, status = ?, priority = ?, present_on_board = ?
      WHERE id = ? RETURNING ${columns}
    `).get(ticket.vikunjaTaskId, ticket.title, ticket.status, ticket.priority, Number(ticket.presentOnBoard), id)
    return readTicket(row)
  }

  // Called inside the board sync transaction before restoring the fetched tickets.
  markAllAbsent(): void {
    this.database.exec("UPDATE tickets SET present_on_board = 0 WHERE present_on_board = 1")
  }

  // Referenced tickets cannot be deleted until their assignments are removed.
  delete(id: number): boolean {
    return this.database.prepare("DELETE FROM tickets WHERE id = ?").run(id).changes > 0
  }
}
