// Persists tickets and looks them up by local ID or unique Vikunja task ID.
import type { DatabaseSync } from "node:sqlite"

// SQLite INTEGER is 64-bit; numeric IDs must fit JavaScript's safe integer range.
export interface TicketRecord {
  id: number
  vikunjaTaskId: number
  title: string
  status: string
  priority: number
}

export type TicketInput = Omit<TicketRecord, "id">

const columns = "id, vikunja_task_id AS vikunjaTaskId, title, status, priority"

// Uses a shared connection; closing it is the caller's responsibility.
export class TicketStore {
  constructor(private readonly database: DatabaseSync) {}

  // Local IDs are generated by SQLite; duplicate Vikunja IDs are rejected.
  create(ticket: TicketInput): TicketRecord {
    return this.database.prepare(`
      INSERT INTO tickets (vikunja_task_id, title, status, priority)
      VALUES (?, ?, ?, ?) RETURNING ${columns}
    `).get(ticket.vikunjaTaskId, ticket.title, ticket.status, ticket.priority) as unknown as TicketRecord
  }

  get(id: number): TicketRecord | undefined {
    return this.database.prepare(`SELECT ${columns} FROM tickets WHERE id = ?`).get(id) as unknown as TicketRecord | undefined
  }

  getByVikunjaTaskId(vikunjaTaskId: number): TicketRecord | undefined {
    return this.database.prepare(`SELECT ${columns} FROM tickets WHERE vikunja_task_id = ?`).get(vikunjaTaskId) as unknown as TicketRecord | undefined
  }

  list(): TicketRecord[] {
    return this.database.prepare(`SELECT ${columns} FROM tickets ORDER BY id`).all() as unknown as TicketRecord[]
  }

  // Replaces mutable fields; returns undefined when the local ID does not exist.
  update(id: number, ticket: TicketInput): TicketRecord | undefined {
    return this.database.prepare(`
      UPDATE tickets SET vikunja_task_id = ?, title = ?, status = ?, priority = ?
      WHERE id = ? RETURNING ${columns}
    `).get(ticket.vikunjaTaskId, ticket.title, ticket.status, ticket.priority, id) as unknown as TicketRecord | undefined
  }

  // Referenced tickets cannot be deleted until their assignments are removed.
  delete(id: number): boolean {
    return this.database.prepare("DELETE FROM tickets WHERE id = ?").run(id).changes > 0
  }
}
